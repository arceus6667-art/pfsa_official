import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const source=ts.transpileModule(fs.readFileSync('lib/start-choice.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {canSubmitWork,A2_SUBMISSIONS_TIME,a2Countdown}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const regular={mode:'regular',start_at:'2026-12-15T00:00:00+05:30',payment_id:null,legacy_access:false};
const before=A2_SUBMISSIONS_TIME-1;
assert.equal(canSubmitWork(regular,before,'A2/2026'),false);
assert.equal(canSubmitWork({...regular,legacy_access:true},before,'A2/2026'),false);
assert.equal(canSubmitWork({...regular,mode:'early'},before,'A2/2026'),false);
assert.equal(canSubmitWork({...regular,mode:'early',payment_id:'saved-order'},before,'A2/2026'),true);
assert.equal(canSubmitWork(regular,A2_SUBMISSIONS_TIME,'A2/2026'),true);
assert.equal(canSubmitWork(regular,A2_SUBMISSIONS_TIME+1,'A2/2026'),true);
assert.equal(canSubmitWork(regular,before,'A1/2026'),true);
assert.equal(canSubmitWork(regular,before,'01/2027'),true);
assert.equal(canSubmitWork(null,A2_SUBMISSIONS_TIME,'A2/2026'),false);
assert.equal(a2Countdown(A2_SUBMISSIONS_TIME-1000),'0d 0h 0m 1s');
assert.equal(a2Countdown(A2_SUBMISSIONS_TIME),'0d 0h 0m 0s');
console.log('PASS: A2 exact midnight IST release, legacy regular lock, prepaid early access, countdown; A1 and later batches retain their current access.');

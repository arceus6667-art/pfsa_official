import ts from 'typescript';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const load=async path=>import('data:text/javascript;base64,'+Buffer.from(ts.transpileModule(fs.readFileSync(path,'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText).toString('base64'));
const start=await load('lib/start-choice.ts'),orders=await load('lib/document-order.ts');
const now=Date.parse('2026-11-12T00:00:00Z');
const choice={mode:'regular',start_at:'2026-11-17T00:00:00+05:30',legacy_access:false,payment_id:null};
assert.equal(start.canSubmitWork(null,now),false);
assert.equal(start.canSubmitWork(choice,now),false);
assert.equal(start.canSubmitWork(choice,Date.parse(choice.start_at)),true);
assert.equal(start.canSubmitWork({...choice,mode:'early'},now),false);
assert.equal(start.canSubmitWork({...choice,mode:'early',payment_id:'pending-payment'},now),true);
assert.equal(start.canSubmitWork({...choice,legacy_access:true},now),true);
assert.equal(start.untilStart(choice.start_at,Date.parse(choice.start_at)),'Your batch is open');
const early={kind:'payment',created_at:'2026-11-12T00:00:00Z',data:{order_type:'early_start',package:'bundle',programme:'cloud',status:'pending'}};
assert.equal(orders.reviewDue(early),null);
const tasks=[1,2,3,4].map(week=>({kind:'submission',created_at:`2026-11-${12+week}T00:00:00Z`,data:{week,programme:'cloud'}}));
assert.equal(orders.reviewDue(early,tasks).toISOString(),'2026-11-16T06:00:00.000Z');
assert.equal(orders.reviewDue(early,tasks.slice(0,3)),null);
assert.equal(orders.orderReady(early,[]),false);
console.log('11 start-choice assertions passed: dates, pending early access, legacy access and post-completion document review.');

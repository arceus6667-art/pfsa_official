import ts from 'typescript';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const load=async path=>import('data:text/javascript;base64,'+Buffer.from(ts.transpileModule(fs.readFileSync(path,'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText).toString('base64'));
const report=await load('lib/admin-report.ts');
const pagination=await load('lib/admin-pagination.ts');
const profile=(id,cohort)=>({id,cohort,name:id,email:id+'@example.com',phone:''});
const application=id=>({kind:'application',user_id:id,data:{programme:'cloud'}});
const submission=(id,week,programme='cloud',status='submitted')=>({kind:'submission',user_id:id,data:{week,programme,status}});
const profiles=[profile('a','Batch 1'),profile('b','Batch 2'),profile('c','')];
const records=[application('a'),application('b'),submission('a',1),submission('a',1),submission('a',2,'cloud','reviewed'),submission('a',3,'mobile'),submission('a',7),submission('b',1)];
assert.equal(report.studentRows(profiles,records,'Batch 1').length,1);
assert.equal(report.studentRows(profiles,records,'Batch 1')[0].submitted,2);
assert.equal(report.studentRows(profiles,records,'Batch 1')[0].reviewed,1);
assert.equal(report.studentRows(profiles,records,'unassigned').length,1);
assert.equal(report.studentRows(profiles,records,'','mobile').length,0);
assert.equal(report.paymentAmount({data:{package:'bundle'}}),200);
assert.equal(report.paymentAmount({data:{package:'199'}}),199);
assert.equal(report.csvText([['=1+1','a"b']]),'\uFEFF"\'=1+1","a""b"');
let calls=0;
const rows=await pagination.readAllRows(async(from)=>{calls++;return{data:Array.from({length:Math.max(0,Math.min(500,1201-from))},(_,i)=>from+i),error:null};});
assert.equal(rows.length,1201);
assert.equal(calls,3);
await assert.rejects(()=>pagination.readAllRows(async()=>({data:null,error:{message:'Denied'}})),/Denied/);
console.log('11 admin report assertions passed: batches, unique valid weeks, domain isolation, amounts, CSV safety and pagination beyond 1,000 records.');
